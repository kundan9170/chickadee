"""The work folder (Amendment 2 B4): the one home for where a
design's documents live and who may write which part.

```
<work.dir>/ docs/chickadee by default (`[work] dir`, the person's)
  README.md the index, appended at landing (B1): the harness's
  <date>-<slug>/ one piece of work, named when it opens (4a)
    README.md its summary and status: the harness's, marked (B4)
    design/README.md, *.md Zeus's, through `doc`
    plan/README.md, tasks/*.md Athena's, through `doc`
    report.md the harness's
```

What is here is pure path work, so every caller asks the same question the same way: Zeus's
`doc`, Athena's, the edit tools' refusal, the shells' put-back. Writing goes through the edit
port (`tools/builtin/doc.py`); the session's open work is its `work` line
(`context/lines.WorkLine`).
"""

