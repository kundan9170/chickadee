Part = Literal["design", "plan"]
PARTS: Final[tuple[Part, ...]] = ("design", "plan")
"""Zeus writes `design/`, Athena `plan/` (decision 10)."""

MARKER: Final = "<!-- written by chickadee: do not edit this file by hand -->"
"""The first line of every file the harness owns in `work.dir` (B4): the index and each work's
own README. A folder whose files carry it is chickadee's to write into."""

DEFAULT_DIR: Final[str] = WorkPolicy().dir
"""`[work] dir` when the person sets none; the config owns it."""

WORK_DIR: Final = "{work_dir}"
"""How a prompt template names `work.dir`: a role is told the folder the harness fences, never
the default's name when another is configured."""


def with_work_dir(text: str, work_dir: str) -> str:
    """`text`, a prompt template, naming `work_dir` where it names `WORK_DIR`. A replace, never
    `str.format`: a template holds other braces (JSON examples) that are not fields. No default:
    a caller that forgets the configured folder fails, never names the default's. Normalised as
    the fence reads it (`in_work`), so `notes/` and `./notes` are told as `notes`."""
    return text.replace(WORK_DIR, PurePosixPath(work_dir).as_posix())


NOTICE_SHOWN: Final = "work-notice"
"""B7's marker under the repository's local state: the one-time notice was shown."""


def notice_once(state: Path, work_dir: str, commit: bool) -> str | None:
    """B7: the line the first design stop of a repository says, once, while `work.commit` is
    on; the marker under `state` (the repository's local root) is written as it is handed out,
    so it is never said twice. Harness bookkeeping, never the tree."""
    if not commit:
        return None
    marker = state / NOTICE_SHOWN
    if marker.exists():
        return None
    write_atomic(marker, b"shown\n")
    return (
        f"the design and its plan will be committed to the branch in {work_dir}/, your request "
        "in it word for word; `work.commit = false` in your engine config keeps them out of "
        "the repository"
    )


def dir_error(value: str) -> str | None:
    """Why `value` cannot be `work.dir`, or None: it is a folder inside the repository, named
    from its root."""
    path = PurePosixPath(value)
    if "\\" in value or path.is_absolute() or value.startswith("~"):
        return f"work.dir {value!r} must be a path from the repository root"
    if any(p in ("..", ".") for p in path.parts) or not path.parts:
        return f"work.dir {value!r} must name a folder inside the repository"
    if path.parts[0] == ".git":
        return f"work.dir {value!r} is inside .git"
    return None


def folder_name(today: date, title: str, taken: Callable[[str], bool]) -> str:
    """`<date>-<slug>` of `title`, never one `taken` says exists (decision 4a): a second work
    with the same title the same day is `-2`, then `-3`."""
    base = f"{today.isoformat()}-{slug(title, 'work')}"
    name, n = base, 1
    while taken(name):
        n += 1
        name = f"{base}-{n}"
    return name


def owned_error(root: Path, work_dir: str) -> str | None:
    """Why `work_dir` cannot be the work folder under `root`, or None (decision 4c, B4; D230
    Amendments 1 and 3), the one home of the rule: a file stands at it or at a folder above it,
    or git ignores what a work would hold there, so no snapshot, commit or undo would see it.
    The harness writes only what it makes in the folder: a new work's folder, named so no
    existing one is taken (`folder_name`) and marked (`work_readme`), and the index while it
    is absent or marked (`handoff.record_works`). Everything else there is the person's: never
    written, and never a reason to refuse, since a refusal on it left no exit the harness
    owns."""
    for part in (Path(work_dir), *Path(work_dir).parents):
        at = root / part
        if at.exists() and not at.is_dir():
            return f"{part} exists and is not a folder; set [work] dir to another path"
    if ignored(root, f"{work_dir}/{_PROBE}"):
        return (
            f"work.dir {work_dir} is ignored by git here, so its files could be neither "
            "recorded nor undone"
        )
    return None


_PROBE: Final = "a-work/design/README.md"
"""A path a work folder holds, to ask git whether it ignores the folder's contents."""

FALLBACK_DIRS: Final = ("notes/chickadee", "design/chickadee", "chickadee-work")
"""The folders offered, in order, when `[work] dir` cannot be used here."""


FOLDER_YES: Final = "yes"
"""`folder_question`'s answer that takes the folder offered; anything else keeps the refusal."""


def folder_question(offered: str, why: str) -> Question:
    """The person's question when the work folder cannot be used here (`why`): use `offered`
    for this repository instead. Its default keeps the refusal, so an
    unattended run changes nothing."""
    return Question(
        id=f"work-folder-{uuid.uuid4().hex[:8]}",
        kind=QuestionKind.WORK_FOLDER,
        text=(
            f"{why}. Use {offered} for this repository instead? The choice is kept for this "
            "clone only, in Chickadee's own files; your engine config and the repository are "
            "not changed."
        ),
        options=(
            Option(key=FOLDER_YES, label=f"use {offered} here"),
            Option(key="no", label="no, I will change [work] dir myself"),
        ),
        default="no",
        evidence=(why,),
    )


def free_work_dir(root: Path, unusable: str) -> str | None:
    """The first of `FALLBACK_DIRS` that can be the work folder under `root` (`owned_error`)
    and is not `unusable`, or None: what the harness offers the person for this repository.
    """
    return next(
        (d for d in FALLBACK_DIRS if d != unusable and owned_error(root, d) is None), None
    )


def marked(path: Path) -> bool:
    """Whether `path` opens with `MARKER`: a file the harness wrote (B4), a work's README or
    the index. One that cannot be read is not."""
    try:
        with path.open(encoding="utf-8") as f:
            return f.readline().strip() == MARKER
    except (OSError, UnicodeDecodeError):
        return False


def work_readme(name: str, title: str) -> str:
    """A work's own README when it opens (decision 5): the harness's, marked. Part 4 writes its
    status from the journal."""
    return f"{MARKER}\n# {title}\n\n`{name}` · open\n"


def part_dir(work_dir: str, name: str, part: Part) -> str:
    """The part's folder, from the repository root."""
    return f"{work_dir}/{name}/{part}"


def file_error(file: str) -> str | None:
    """Why `file` cannot name a document in a part, or None (decision 8): a relative path that
    stays inside it. A link out is the caller's to judge, against the disk."""
    if not file or "\\" in file or "\0" in file:
        return f"{file!r} is not a file path"
    path = PurePosixPath(file)
    if path.is_absolute():
        return f"{file} is absolute"
    if any(p in ("..", ".") for p in path.parts):
        return f"{file} leaves your folder"
    return None


NAME_FROM_FOLDER: Final = (
    "name the file from your folder, as README.md or tasks/T1-<slug>.md, with no leading /, "
    ".. or ."
)
"""What a `doc` path that cannot name a document in the caller's part is told."""

MARKDOWN_ONLY: Final = (
    "design files are Markdown: describe the behaviour, the interfaces and the edge cases, "
    "with short pseudocode where it helps; the worker writes the code"
)
"""D214 decision 1's refusal: a design holding the implementation makes the worker retype it."""


def markdown_error(file: str) -> str | None:
    """Why `doc` may not write `file`, or None: `design/` and `plan/` hold
    Markdown only, whatever else they once held."""
    if PurePosixPath(file).suffix.lower() == ".md":
        return None
    return f"{file} is not a .md file"


def leaves(root: Path, folder: str, file: str) -> bool:
    """Whether `file` under `folder` lands outside it once links resolve: a link out. The
    folder itself counts as inside, as `paths.within` counts a root."""
    return within(root / folder, file) is None


def resolve(root: Path, work: WorkLine | None, part: Part, file: str) -> str | DraftRefused:
    """`file`'s path from the repository root in `part` of the open `work`, or why not: the one
    check every `doc` call passes (decision 8), Zeus's and Athena's."""
    if work is None:
        # Reached by Athena alone: Zeus's port opens a work before it resolves a file.
        return DraftRefused(
            "DENIED",
            "no work folder is open, so there are no plan files",
            do="send the whole plan as plan's text instead",
        )
    why = file_error(file)
    if why is not None:
        return DraftRefused("DENIED", why, do=NAME_FROM_FOLDER)
    folder = part_dir(work.dir, work.name, part)
    if leaves(root, folder, file):
        return DraftRefused("DENIED", f"{file} leads out of your folder", do=NAME_FROM_FOLDER)
    return f"{folder}/{file}"


def in_work(path: str, work_dir: str) -> bool:
    """Whether the repository path `path` is in `work_dir`: the edit tools refuse it, and a
    shell command's write there is put back (decision 10)."""
    # Folded: on a case-insensitive disk (macOS, Windows) `Docs/Chickadee` is the same folder.
    parts = PurePosixPath(path.casefold()).parts
    mine = PurePosixPath(work_dir.casefold()).parts
    return parts[: len(mine)] == mine


# -- the shape (Amendment 1, A1-A6) ----------------------------------------------------------

_HEADING: Final = re.compile(r"^## +(.+?)\s*$")
_PLACEHOLDER: Final = re.compile(r"^\s*<.*>\s*$")
_FENCE: Final = re.compile(r"^\s*(```|~~~)")
_FILE_LINE: Final = re.compile(r"^- \[([^\]]+)\]\(([^)]+)\): +(\S.*)$")
_TASK_LINE: Final = re.compile(
    r"^(\d+)\. \[(T[0-9.]+): ([^\]]+)\]\((tasks/[^)]+)\): +(\S.*?)\.? *"
    r"Depends on: *(\S.*)$"
)
"""A `Tasks` line. Its id is only found here; what an id may be is `TASK_ID_RE`'s alone, which
`_id_errors` checks."""
_NONE: Final = "none."


def sections(text: str) -> dict[str, str]:
    """`text`'s `##` sections by heading, lowercased (A2: matched by text, ignoring case), each
    to its body; a heading inside a fenced block is the block's, not a section."""
    out: dict[str, str] = {}
    current: str | None = None
    body: list[str] = []
    fenced = False
    for line in text.splitlines():
        if _FENCE.match(line):
            fenced = not fenced
        found = None if fenced else _HEADING.match(line)
        if found is not None:
            if current is not None:
                out[current] = "\n".join(body).strip()
            current, body = found.group(1).strip().lower(), []
        elif current is not None:
            body.append(line)
    if current is not None:
        out[current] = "\n".join(body).strip()
    return out


def required(template: str) -> tuple[str, ...]:
    """The template's `##` headings, as written: the minimum a file of it holds (A1, A2)."""
    return tuple(
        m.group(1).strip()
        for line in template.splitlines()
        if (m := _HEADING.match(line)) is not None
    )


def unfilled(text: str, template: str) -> list[str]:
    """Each of the template's sections `text` lacks or leaves unfilled (A3): absent, empty once
    its `<…>` placeholders are set aside, or the template's own body unchanged. Extra sections
    and their order are never checked (A2).

    A section the template writes with no `<…>` placeholder is fixed text, there to be copied
    (the brief's `Report`, the worker's instruction): kept as written, it is filled. Counted as
    unfilled, nothing could pass it but rewording it (2026-10-23)."""
    have = sections(text)
    theirs = sections(template)
    out: list[str] = []
    for heading in required(template):
        key = heading.lower()
        body = have.get(key)
        given = theirs.get(key, "")
        fixed = not any(_PLACEHOLDER.match(line) for line in given.splitlines())
        if body is None:
            copy = ": copy it from the template as it is" if fixed else ""
            out.append(f"the {heading} section is missing{copy}")
            continue
        kept = "\n".join(line for line in body.splitlines() if not _PLACEHOLDER.match(line))
        if not kept.strip() or (body == given and not fixed):
            out.append(f"the {heading} section is not filled in")
    return out


def title_of(text: str) -> str | None:
    """A Markdown file's title: its first `# ` heading, None when it has none. The one reading
    of a work's, a README's or a brief's title."""
    return next((line[2:].strip() for line in text.splitlines() if line.startswith("# ")), None)


def _files(folder: Path, *, under: str = "") -> set[str]:
    """Every file under `folder`, by its path from it, `README.md` and `under` aside."""
    if not folder.is_dir():
        return set()
    found = {p.relative_to(folder).as_posix() for p in folder.rglob("*") if p.is_file()}
    return {f for f in found if f != "README.md" and not (under and f.startswith(under))}


def design_files(text: str) -> tuple[tuple[str, str], ...]:
    """The design README's `Files` lines that are well formed, as `(file, line)` (A4): what
    Athena's head and the worker's brief name each file by (A7)."""
    body = sections(text).get("files", "")
    return tuple(
        (m.group(2), m.group(3).strip())
        for line in body.splitlines()
        if (m := _FILE_LINE.match(line.strip())) is not None and m.group(1) == m.group(2)
    )


def design_errors(folder: Path, template: str) -> list[str]:
    """What is wrong with `design/` at `folder` (A5): its README's minimum sections filled, and
    its `Files` the folder's other files exactly, each with its line, both ways (A4)."""
    readme = folder / "README.md"
    if not readme.is_file():
        return ["design/README.md does not exist: write it first with doc"]
    text = readme.read_text(encoding="utf-8")
    out = [f"design/README.md: {why}" for why in unfilled(text, template)]
    body = sections(text).get("files")
    if body is None:
        return out
    listed: set[str] = set()
    for line in body.splitlines():
        if not line.strip() or _PLACEHOLDER.match(line) or line.strip().lower() == _NONE:
            continue
        found = _FILE_LINE.match(line.strip())
        if found is None or found.group(1) != found.group(2):
            out.append(
                f"design/README.md Files: {line.strip()!r} is not `- [name](name): line`"
            )
            continue
        listed.add(found.group(2))
    present = _files(folder)
    out += [
        f"design/README.md Files lists {f}, which design/ does not hold"
        for f in sorted(listed - present)
    ]
    out += [
        f"design/{f} is not listed under Files in design/README.md"
        for f in sorted(present - listed)
    ]
    return out


def plan_tasks(text: str) -> tuple[tuple[str, str, str], ...]:
    """The plan README's `Tasks` lines that are well formed, as `(id, title, file)`: what
    `delegate(task)` resolves an id through (decision 14)."""
    body = sections(text).get("tasks", "")
    return tuple(
        (m.group(2), m.group(3).strip(), m.group(4))
        for line in body.splitlines()
        if (m := _TASK_LINE.match(line.strip())) is not None
    )


def approved_plans(run: RunProjection) -> tuple[PlanWrittenP, ...]:
    """Every version of the plan the run approved or revised, in order (decision 14); a
    cancelled one is not a plan. Version `n` is pinned as `plan_pin(…, n)`."""
    return tuple(p.payload for p in run.lines(PlanWrittenP) if p.payload.outcome == "approved")


def pin_plan(root: Path, tree: str, folder: str, run_id: str, version: int) -> None:
    """Pin `tree`, `folder` as the person approved it, as the run's plan version `version`."""
    pin_tree(root, tree, folder, run_id, _plan_pin_name(version))


def plan_pin(root: Path, run_id: str, version: int) -> str | None:
    """The tree the run pinned as its plan version `version`, or None."""
    return pin_of(root, run_id, _plan_pin_name(version))


def plan_ids(root: Path, pins: Sequence[str | None]) -> dict[str, str]:
    """Every task id the pinned plans list, by its file, the first pin's first: an id keeps the
    file it was first approved with."""
    held: dict[str, str] = {}
    for tree in pins:
        readme = pinned_text(root, tree, "README.md") if tree else None
        for task, _title, file in plan_tasks(readme or ""):
            held.setdefault(task, file)
    return held


def _plan_pin_name(version: int) -> str:
    return f"plan-v{version}"


def plan_errors(
    folder: Path,
    template: str,
    brief: str,
    *,
    approved: Mapping[str, str] | None = None,
    delegated: Collection[str] = (),
) -> list[str]:
    """What is wrong with `plan/` at `folder` (decision 13, A4, A6): its
    README's minimum sections filled; its `Tasks` one line per task, each id unique and a
    top-level `T<n>` or a piece of a task listed before it (`T3.1` after `T3`), each depending
    on earlier ones, each linking its own file in `tasks/`; no file there unlisted; and each
    task file titled as its line, with the brief template's sections filled.

    Ids are stable, not sequential: `approved` is every id an approved version of this plan
    held, by its file, and an id keeps its file, so it is never given to another task;
    `delegated` is every id a delegation ran, which never leaves the plan."""
    readme = folder / "README.md"
    if not readme.is_file():
        return ["plan/README.md does not exist: write it first with doc"]
    text = readme.read_text(encoding="utf-8")
    out = [f"plan/README.md: {why}" for why in unfilled(text, template)]
    body = sections(text).get("tasks", "")
    seen: list[str] = []
    files: set[str] = set()
    for line in body.splitlines():
        line = line.strip()
        if not line or _PLACEHOLDER.match(line):
            continue
        found = _TASK_LINE.match(line)
        if found is None:
            out.append(
                f"plan/README.md Tasks: {line!r} is not "
                "`<n>. [T<n>: <title>](tasks/T<n>-<slug>.md): one line. Depends on: <ids>`"
            )
            continue
        n, task, title, file, _, depends = found.groups()
        if file_error(file) is not None or within(folder, file) is None:
            out.append(f"plan/README.md Tasks: {task}'s file {file} leaves plan/")
            continue
        if n != str(len(seen) + 1):
            out.append(
                f"plan/README.md Tasks: {task}'s line is numbered {n}, not {len(seen) + 1}"
            )
        out += _id_errors(task, seen, file, approved or {})
        if not file.startswith(f"tasks/{task}-"):
            out.append(
                f"plan/README.md Tasks: {task}'s file {file} is not tasks/{task}-<slug>.md"
            )
        named = [d.strip() for d in depends.rstrip(".").split(",")]
        if named != ["none"]:
            out += [
                f"plan/README.md Tasks: {task} depends on {d}, which is not an earlier task"
                for d in named
                if d not in seen
            ]
        seen.append(task)
        files.add(file)
        path = folder / file
        if not path.is_file():
            out.append(f"plan/{file} does not exist, though Tasks lists {task}")
            continue
        brief_text = path.read_text(encoding="utf-8")
        if title_of(brief_text) != f"{task}: {title.strip()}":
            out.append(f"plan/{file}: its title is not `# {task}: {title.strip()}`, its line's")
        out += [f"plan/{file}: {why}" for why in unfilled(brief_text, brief)]
    if not seen and not any("Tasks" in o for o in out):
        out.append("plan/README.md Tasks lists no task")
    out += [
        f"plan/README.md Tasks: {task} was delegated, so it stays in the plan"
        for task in sorted(set(delegated) - set(seen))
    ]
    present = {f"tasks/{f}" for f in _files(folder / "tasks")}
    out += [
        f"plan/{f} is not listed under Tasks in plan/README.md" for f in sorted(present - files)
    ]
    return out


def _id_errors(
    task: str, seen: Sequence[str], file: str, approved: Mapping[str, str]
) -> list[str]:
    """One `Tasks` line's id against the lines before it and the approved versions."""
    out: list[str] = []
    if TASK_ID_RE.match(task) is None:
        # `delegate` would be refused an id the plan was approved with.
        out.append(
            f"plan/README.md Tasks: {task} is not a task id: T and a number from 1, then at "
            "most four pieces, each a dot and a number from 1 (T3, T3.1)"
        )
    if task in seen:
        out.append(f"plan/README.md Tasks: {task} is listed twice; each task has its own id")
    parent = parent_of(task)
    if parent is not None and parent not in seen:
        out.append(
            f"plan/README.md Tasks: {task} is a piece of {parent}, which is not listed "
            "before it"
        )
    was = approved.get(task)
    if was is not None and was != file:
        out.append(
            f"plan/README.md Tasks: {task} was {was} in an approved plan, and an id keeps its "
            "task: keep that file, or give this task a new id"
        )
    return out


def works(state: SessionState) -> tuple[WorkLine, ...]:
    """Every `work` line of the session, in order: each work opened, then how it closed. The
    one home of reading them (decision 4a); the session's fold keeps them unread."""
    return tuple(record for _, record in state.lines() if isinstance(record, WorkLine))


def open_work(state: SessionState) -> WorkLine | None:
    """The session's open work (decision 4a): the latest `work` line, while it is open."""
    found = works(state)
    return found[-1] if found and found[-1].state == "open" else None


def record_work(session: Session, line: WorkLine) -> int:
    """`line` on the session's log, under its lock: a work opened, or how it closed."""
    with session.lock:
        return session.append(line).seq
