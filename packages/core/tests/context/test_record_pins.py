"""Pins of every session-log line, before the records theme changes how lines are read.

D151 moves every writer onto a typed append and every reader onto a type that parses the
blob's bytes. These pin what that must not change, through the one surface it keeps: the
files on disk.

- **The bytes.** A scripted session writes every kind `context/` owns through its public
  writer, and each blob's bytes must equal the recording in `fixtures/records/`.
- **The fold.** The recording, written back to disk, opens to a pinned state.
- **The shapes.** One payload per row, accepted or refused field by field, through a log
  written by hand and opened, so the row survives whatever replaces `SessionState.check`'s
  signature.

A later task may change these tests' setup when the code they call changes shape, never their
assertions.
"""

