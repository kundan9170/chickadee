@pytest.mark.parametrize(
    ("before", "kind", "payload", "opens"),
    [pytest.param(b, k, p, o, id=i) for i, b, k, p, o in ROWS],
)
def test_a_line_is_read_as_it_was_before(
    tmp_path: Path,
    before: list[Mapping[str, Any]],
    kind: str,
    payload: Mapping[str, Any] | str,
    opens: bool,
) -> None:
    root = tmp_path / "sessions"
    lines: list[dict[str, Any]] = [
        {"session": PARENT, "kind": "turn", "run_id": None, "bytes": _canonical(p)}
        for p in before
    ]
    text = payload if isinstance(payload, str) else _canonical(payload)
    run = RUN if kind == "episode" else None
    lines.append({"session": PARENT, "kind": kind, "run_id": run, "bytes": text})
    materialise(root, lines)
    if opens:
        Session.open(root, PARENT).close()
    else:
        with pytest.raises(SessionCorrupt) as raised:
            Session.open(root, PARENT).close()
        assert raised.value.seq == len(lines)


def _canonical(payload: Mapping[str, Any]) -> str:
    return json.dumps(payload, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
