def test_every_writer_writes_the_bytes_it_wrote_before(tmp_path: Path) -> None:
    ws = tmp_path / "ws"
    ws.mkdir()
    scenario(tmp_path / "sessions", ws)
    assert recorded(tmp_path / "sessions") == recording()


def test_the_recording_covers_every_kind_context_writes() -> None:
    kinds = {line["kind"] for line in recording()}
    assert kinds >= {
        "turn",
        "tool",
        "workspace",
        "constraint",
        "rejected",
        "concern",
        "spend",
        "cap",
        "episode",
        "compaction",
        "fork",
    }


# -- the fold -------------------------------------------------------------------------------


def _state(root: Path, sid: str) -> dict[str, Any]:
    s = Session.open(root, sid)
    try:
        st = s.state
        spent = family_spent(root, sid, st)
        return {
            "last_seq": st.last_seq,
            "turns": [(t.seq, t.role) for t in st.turns()],
            "pending": list(st.pending_calls()),
            "ran": {c: st.ran(c) for c in ("c1", "c2", "k1")},
            "views": [(v.handle_id, [str(x) for x in v.spans], v.call_id) for v in st.views()],
            "constraints": [c.id for c in st.ledger.live_constraints()],
            "rejected": [r.id for r in st.ledger.rejections()],
            "reconsidered": len(st.ledger.reconsiderations("R-1")),
            "episodes": [
                # A new episode carries no tier; a recorded one keeps its own.
                (e.run_id, e.path, e.tier.value if e.tier else None, e.opened_at_seq)
                for e in st.episodes()
            ],
            "workspace": _workspace(st.workspace_at(st.last_seq)),
            "boundary": st.boundary,
            "forked_from": st.forked_from,
            "caps": [(c.hard_cost_usd, c.rung) for c in lines_of(st, CapLine)],
            "spent": (spent.tokens_in, spent.tokens_out, spent.cached_in, spent.cost_usd),
            "estimated": spent.estimated_calls,
            "rungs": [c.rung for c in lines_of(st, SpendLine)],
            "concerns": [c.id for c in st.concerns.all()],
            "live_concerns": [c.id for c in st.concerns.live()],
        }
    finally:
        s.close()


def _workspace(ref: WorkspaceRef | None) -> tuple[object, ...] | None:
    if ref is None:
        return None
    return (ref.mode, ref.lease_id, ref.source_head, ref.branch, ref.worktree_path, ref.handoff)


def test_the_recording_opens_to_its_pinned_state(tmp_path: Path) -> None:
    root = tmp_path / "sessions"
    materialise(root, recording())
    parent = _state(root, PARENT)
    child = _state(root, CHILD)
    assert parent == PINNED_PARENT
    assert child["forked_from"] == (PARENT, parent["last_seq"])
    assert child["constraints"] == parent["constraints"]
    assert child["spent"] == parent["spent"]


