"""A `fork` payload carries the wall-clock time it was made: the one value the recording masks,
so the pin holds the shape and `T-3.59` can change the clock without a new recording."""


# -- the scenario ----------------------------------------------------------------------------


def scenario(root: Path, ws: Path) -> None:
    """Every kind `context/` writes, through the writer each has today, with fixed inputs."""
    s = Session.create(root, PARENT)
    said = s.record_user("keep the cache per user")
    s.record_workspace(
        WorkspaceRef(
            mode="worktree",
            lease_id="L-pin",
            source_ref="main",
            source_head="a" * 40,
            branch="chickadee/S-pin",
            worktree_path="/worktrees/S-pin",
            handoff="pending",
        )
    )
    s.record_assistant(
        "looking",
        [ToolCall(id="c1", name="read", arguments={"target": "cache.py", "lines": "1-3"})],
    )
    shape = Shape(bytes=30, lines=3, symbols=1, kind="python")
    handle = Handle(
        id="h_00aa11bb",
        kind="file",
        shape=shape,
        preview="def get(key):",
        ops=("read", "grep_in"),
        content_sha="c" * 64,
        path="cache.py",
        run_id=None,
        seqs=None,
    )
    s.record_tool(
        "c1", ToolResult(handle=handle, content="def get(key):\n", view=(Span(1, 3),))
    )
    s.record_assistant("noted", findings={"c1": "the cache is global"})
    s.record_assistant(
        "looking again", [ToolCall(id="c2", name="shell", arguments={"command": "ls"})]
    )
    s.record_tool("c2", "cache.py", ran=False)
    assert note_constraint(s, "the cache is per user", [said.seq], "session") == "C-1"
    assert (
        note_rejected(s, text="a global cache", reason="it leaks", by="zeus", at=said.seq)
        == "R-1"
    )
    reconsider(s, "R-1", "the scope changed", "user")
    assert note_concern(s, "the cache may leak", ["cache.py"], "critic") == "K-1"
    accrue(s, ["cache.py"], run_id=RUN)
    promote(s, "K-1", "c-cache-check")
    assert note_concern(s, "the key may collide", ["keys.py"], "zeus") == "K-2"
    dismiss(s, "K-2", by="user")
    # The rung a line written in older versions names: the log takes any well-formed name.
    s.record_spend("model-a", Usage(prompt_tokens=100, completion_tokens=20), 0.25, "zeus")
    s.record_spend(
        "model-b",
        Usage(
            prompt_tokens=7,
            completion_tokens=3,
            cached_prompt_tokens=5,
            cache_write_tokens=2,
            estimated=True,
        ),
        1,
        rung="planner",
    )
    s.record_cap(5.0)
    s.record_cap(None)
    s.record_cap(2.5, rung="coder")
    dispatch = s.record_assistant(
        "dispatching",
        [ToolCall(id="k1", name="coder", arguments={"request": {"task": "make it per user"}})],
    )
    s.record_episode(
        EpisodeLine(
            run_id=RUN,
            path="exact",
            tier=Tier.T1,
            design_sha=None,
            constraints=("C-1",),
            opened_at_seq=dispatch.seq,
        )
    )
    s.record_tool("k1", "done: the cache is per user", run_id=RUN)
    s.record_notice(Notice(NoticeTrigger.RUN_ENDED, "run ended with work not applied"))
    work_unit(s, "alpha")
    work_unit(s, "beta")
    s.record_user("thanks")
    s.record_assistant("welcome")
    assert cut(s, ws).cut is not None
    last = s.state.last_seq
    s.close()
    Session.fork(root, PARENT, last, "try another way", CHILD, code="keep").close()


def recorded(root: Path) -> list[dict[str, Any]]:
    """Every line of both sessions as the recording holds it, the blob's bytes as text."""
    out: list[dict[str, Any]] = []
    for sid in (PARENT, CHILD):
        directory = session_dir(root, sid)
        for raw in (directory / "session.jsonl").read_text(encoding="utf-8").splitlines():
            line = json.loads(raw)
            blob = (directory / "blobs" / line["payload_sha"]).read_bytes().decode("utf-8")
            if line["kind"] == "fork":
                blob = STAMP.sub(f'"at":"{AT}"', blob)
            out.append(
                {"session": sid, "kind": line["kind"], "run_id": line["run_id"], "bytes": blob}
            )
    return out


def recording() -> list[dict[str, Any]]:
    return [json.loads(line) for line in RECORDING.read_text(encoding="utf-8").splitlines()]


def materialise(root: Path, lines: Sequence[Mapping[str, Any]]) -> None:
    """The lines written to disk as the store writes them, every blob beside its log, a fork's
    after its parent's."""
    seqs: dict[str, int] = {}
    for line in lines:
        sid = str(line["session"])
        if sid not in seqs and line["kind"] == "fork":
            # A fork's own lines continue its parent's numbering, after the fork point.
            seqs[sid] = json.loads(str(line["bytes"]))["forked_from"]["at_seq"]
        directory = session_dir(root, sid)
        (directory / "blobs").mkdir(parents=True, exist_ok=True)
        data = str(line["bytes"]).encode("utf-8")
        sha = sha256_hex(data)
        (directory / "blobs" / sha).write_bytes(data)
        seqs[sid] = seqs.get(sid, 0) + 1
        entry = {
            "seq": seqs[sid],
            "at": AT,
            "kind": line["kind"],
            "payload_sha": sha,
            "run_id": line["run_id"],
        }
        with (directory / "session.jsonl").open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(entry, ensure_ascii=False, separators=(",", ":")) + "\n")


